class BoqConflictError(ValueError):
    """A user-actionable conflict that should surface as HTTP 409."""


def get_snapshot(
    db: Session, project_id: str, package_id: str | None = None
) -> BoqSnapshot | None:
    """Return the active snapshot for one package (NULL = legacy project-wide)."""
    statement = select(BoqSnapshot).where(BoqSnapshot.project_id == project_id)
    if package_id is None:
        statement = statement.where(BoqSnapshot.package_id.is_(None))
    else:
        statement = statement.where(BoqSnapshot.package_id == package_id)
    return db.scalar(statement.order_by(BoqSnapshot.created_at.desc()))


def resolve_package(
    db: Session, project: Project, package_id: str | None
) -> BidPackage | None:
    """Validate the requested package against the project's package mode.

    Raises ``ValueError`` (mapped to HTTP 400) when the project has no packages
    but one was requested, or when packages exist but none was named. An id that
    does not belong to this project raises ``LookupError`` (HTTP 404).
    """

    wanted = (package_id or "").strip() or None
    packages = list(
        db.scalars(
            select(BidPackage)
            .where(BidPackage.project_id == project.id)
            .order_by(BidPackage.position, BidPackage.created_at)
        )
    )
    if not packages:
        if wanted is not None:
            raise ValueError("该项目尚未启用包件，不能指定包件")
        return None
    if wanted is None:
        raise ValueError("该项目已启用包件，请指定包件")
    for package in packages:
        if package.id == wanted:
            return package
    raise LookupError(f"包件不存在：{wanted}")



def _unlink_source(project: Project, source: SourceFile) -> None:
    stored = Path(source.stored_path).expanduser()
    sources_dir = (settings.project_dir(project.id) / "sources").resolve()
    try:
        resolved = stored.resolve()
    except OSError:  # pragma: no cover - unreadable path
        return
    if sources_dir == resolved.parent or sources_dir in resolved.parents:
        resolved.unlink(missing_ok=True)


def remove_snapshot(
    db: Session, project: Project, *, package_id: str | None = None, delete_file: bool = True
) -> bool:
    snapshot = get_snapshot(db, project.id, package_id)
    if snapshot is None:
        return False
    source = db.get(SourceFile, snapshot.source_file_id) if snapshot.source_file_id else None
    db.delete(snapshot)
    db.flush()
    if source is not None and source.project_id == project.id:
        if delete_file:
            _unlink_source(project, source)
        db.delete(source)
        db.flush()
    return True


def import_boq(
    db: Session,
    project: Project,
    path: str | Path,
    sheet: str | None = None,
    *,
    package_id: str | None = None,
) -> BoqSnapshot:
    """Parse a workbook and replace the active snapshot of one package."""
    parsed = parse_boq(path, sheet=sheet)
    remove_snapshot(db, project, package_id=package_id)
    source = add_source(db, project, path, role="boq")
    source.parse_state = "parsed"
    source.parse_note = f"sheet={parsed.sheet}, rows={len(parsed.items)}"
    snapshot = BoqSnapshot(
        project_id=project.id,
        package_id=package_id,
        source_file_id=source.id,
        filename=source.filename,
        sheet=parsed.sheet,
        header_row=parsed.header_row,
        items=parsed.items,
        warnings=parsed.warnings,
        ignored=[],
        prices={},
    )
    db.add(snapshot)
    db.flush()
    return snapshot


def _snapshot_payload(snapshot: BoqSnapshot) -> dict[str, Any]:
    created = snapshot.created_at
    return {
        "id": snapshot.id,
        "package_id": snapshot.package_id,
        "filename": snapshot.filename,
        "sheet": snapshot.sheet,
        "header_row": snapshot.header_row,
        "item_count": len(snapshot.items or []),
        "warnings": list(snapshot.warnings or []),
        "created_at": created.isoformat() if created else None,
    }


def build_payload(
    db: Session, project_id: str, package_id: str | None = None
) -> dict[str, Any]:
    """Build the alignment payload shared by GET / POST / apply."""
    project = db.get(Project, project_id)
    policy = get_price_policy(project)
    snapshot = get_snapshot(db, project_id, package_id)
    materials = list(
        db.scalars(
            select(Material).where(Material.project_id == project_id).order_by(Material.id)
        )
    )
    if snapshot is None:
        summary = dict(EMPTY_SUMMARY)
        summary["adjusted_total"] = _adjusted_total(summary, policy)
        _apply_tax(summary, policy)
        return {
            "snapshot": None,
            "rows": [],
            "summary": summary,
            "ledger_summary": {
                "materials": len(materials),
                "matched": 0,
                "missing_in_boq": len(materials),
            },
            "price_policy": policy,
        }
    items = list(snapshot.items or [])
    rows = align(
        items,
        materials,
        list(snapshot.ignored or []),
        snapshot.sheet,
        dict(snapshot.prices or {}),
    )
    summary = _summarize(rows, len(items))
    summary["adjusted_total"] = _adjusted_total(summary, policy)
    _apply_tax(summary, policy)
    ledger_summary = {
        "materials": len(materials),
        "matched": len(materials) - summary["missing_in_boq"],
        "missing_in_boq": summary["missing_in_boq"],
    }
    return {
        "snapshot": _snapshot_payload(snapshot),
        "rows": rows,
        "summary": summary,
        "ledger_summary": ledger_summary,
        "price_policy": policy,
    }


