def quota_payload(quota: QuotaItem) -> dict[str, Any]:
    created = quota.created_at
    updated = quota.updated_at
    return {
        "id": quota.id,
        "name": quota.name,
        "spec": quota.spec or "",
        "unit": quota.unit or "",
        "unit_price": money.unit_price(quota.unit_price or 0.0),
        "category": quota.category or "",
        "note": quota.note or "",
        "created_at": clock.iso_utc(created),
        "updated_at": clock.iso_utc(updated),
    }


def match_quotas(
    item: dict[str, Any], quotas: list[QuotaItem], *, limit: int | None = None
) -> list[tuple[float, QuotaItem]]:
    """Score every quota against one BOQ-like item, best first (threshold 0.75)."""
    scored: list[tuple[float, QuotaItem]] = []
    for quota in quotas:
        score = match_score(item, quota)
        if score >= MATCH_THRESHOLD:
            scored.append((score, quota))
    scored.sort(key=lambda pair: (-pair[0], pair[1].name, pair[1].id))
    if limit is not None:
        scored = scored[:limit]
    return scored


def quota_fill(
    db: Session,
    project: Project,
    *,
    package_id: str | None = None,
    only_missing: bool = True,
    dry_run: bool = True,
) -> dict[str, Any]:
    """Propose (and optionally write) administrator-maintained quota prices.

    A row only receives a price when a quota scores at least
    :data:`MATCH_THRESHOLD`; the application never derives or invents a price.
    """
    snapshot = get_snapshot(db, project.id, package_id)
    if snapshot is None:
        raise BoqConflictError("尚未上传工程量清单，请先导入清单文件")
    quotas = list(db.scalars(select(QuotaItem).order_by(QuotaItem.name, QuotaItem.id)))
    items = list(snapshot.items or [])
    prices = dict(snapshot.prices or {})
    ignored = set(snapshot.ignored or [])
    proposals: list[dict[str, Any]] = []
    applied = 0
    for item in items:
        key = f"{snapshot.sheet}!{item['row']}"
        if key in ignored:
            continue
        best = match_quotas(item, quotas, limit=1)
        if not best:
            continue
        score, quota = best[0]
        proposals.append(
            {
                "boq_row": item["row"],
                "name": item.get("name", ""),
                "quota_id": quota.id,
                "quota_name": quota.name,
                "unit_price": money.unit_price(quota.unit_price or 0.0),
                "score": round(float(score), 4),
            }
        )
        if dry_run:
            continue
        if only_missing and _price_payload(item, prices.get(key)) is not None:
            continue
        prices[key] = money.unit_price(quota.unit_price or 0.0)
        applied += 1
    if not dry_run and applied:
        snapshot.prices = prices
        db.flush()
    return {"proposals": proposals, "applied": applied}


def adjust_prices(
    db: Session, project: Project, *, package_id: str | None = None
) -> dict[str, Any]:
    """Multiply every entered unit price by the policy factor and write it back."""
    snapshot = get_snapshot(db, project.id, package_id)
    if snapshot is None:
        raise BoqConflictError("尚未上传工程量清单，请先导入清单文件")
    policy = get_price_policy(project)
    factor = float(policy["factor"])
    digits = int(policy["round_digits"])
    prices = dict(snapshot.prices or {})
    rows = 0
    for item in list(snapshot.items or []):
        key = f"{snapshot.sheet}!{item['row']}"
        price = _price_payload(item, prices.get(key))
        if price is None:
            continue
        prices[key] = money.adjusted_total(price["unit_price"], factor, digits)
        rows += 1
    if rows == 0:
        raise BoqConflictError("该包件尚未录入任何单价，无法调价")
    snapshot.prices = prices
    db.flush()
    return {
        "rows": rows,
        "factor": factor,
        "payload": build_payload(db, project.id, package_id),
    }
