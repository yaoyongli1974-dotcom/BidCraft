"""Excel 工程量清单（BOQ）导入、双向对齐、报价与响应导出。

The module is deliberately independent from ``parsing.loader._read_xlsx``: a
tender bill of quantities must keep its original column positions (blank spec /
unit cells are meaningful) and its merged header cells must be readable, so the
reader below works on a positional grid instead of a trimmed table.

No price, brand or model numbers are generated by the application: unit prices
are entered by the user, and every other value comes from the uploaded workbook
or from the project's material ledger.
"""

