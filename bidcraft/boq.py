# --------------------------------------------------------------------- parser

HEADER_SCAN_ROWS = 30
NAME_ALIASES = ("材料名称", "设备名称", "货物名称", "项目名称", "名称")
SPEC_ALIASES = ("规格型号", "规格及型号", "技术参数", "规格", "型号")
UNIT_ALIASES = ("计量单位", "单位")
QTY_ALIASES = ("工程量", "数量")
SEQ_ALIASES = ("序号",)
NOTE_ALIASES = ("备注", "说明")

FIELD_ALIASES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("seq", SEQ_ALIASES),
    ("name", NAME_ALIASES),
    ("spec", SPEC_ALIASES),
    ("unit", UNIT_ALIASES),
    ("qty", QTY_ALIASES),
    ("note", NOTE_ALIASES),
)

_NUMBER_RE = re.compile(r"-?\d+(?:\.\d+)?")
_DROP_CHARS = set("（）()【】[]，,。.;；:：、“”\"'《》<>~-—/\\|·`!！?？*#&+％%")
_QTY_BLANK = {"", "-", "—", "/", "无"}


@dataclass(slots=True)
class ParsedBoq:
    sheet: str
    header_row: int
    items: list[dict[str, Any]]
    warnings: list[str]


def _text(value: Any) -> str:
    """Render a cell value as trimmed text without losing integer formatting."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value).strip()


def _header_key(value: Any) -> str:
    text = unicodedata.normalize("NFKC", _text(value)).lower()
    return "".join(ch for ch in text if not ch.isspace())


def _field_of(value: Any) -> str | None:
    key = _header_key(value)
    if not key:
        return None
    for field, aliases in FIELD_ALIASES:
        for alias in aliases:
            if key == alias or alias in key or key in alias:
                return field
    return None


def parse_qty(value: Any) -> tuple[float | None, bool]:
    """Parse a quantity cell. Returns ``(qty, ok)``; ``ok`` is False when the
    text is present but not a number (caller turns that into a warning)."""
    if value is None:
        return None, True
    if isinstance(value, bool):
        return None, False
    if isinstance(value, (int, float)):
        return float(value), True
    raw = _text(value)
    if not raw or raw in _QTY_BLANK:
        return None, True
    cleaned = re.sub(r"[\s,，]", "", unicodedata.normalize("NFKC", raw))
    match = _NUMBER_RE.search(cleaned)
    if match is None:
        return None, False
    return float(match.group()), True


def _sheet_grid(sheet) -> list[list[Any]]:
    """Read the sheet into a positional grid, propagating merged header values."""
    rows = sheet.max_row or 0
    cols = sheet.max_column or 0
    if rows <= 0 or cols <= 0:
        return []
    grid: list[list[Any]] = [
        [sheet.cell(row=r, column=c).value for c in range(1, cols + 1)]
        for r in range(1, rows + 1)
    ]
    for merged in sheet.merged_cells.ranges:
        value = grid[merged.min_row - 1][merged.min_col - 1]
        if value is None:
            continue
        for r in range(merged.min_row - 1, merged.max_row):
            for c in range(merged.min_col - 1, merged.max_col):
                grid[r][c] = value
    return grid


def _find_header(grid: list[list[Any]]) -> tuple[int, dict[str, int]] | None:
    for index, row in enumerate(grid[:HEADER_SCAN_ROWS]):
        mapping: dict[str, int] = {}
        for column, value in enumerate(row):
            field = _field_of(value)
            if field and field not in mapping:
                mapping[field] = column
        signals = len({"name", "spec", "unit", "qty"} & set(mapping))
        if signals >= 2 and "name" in mapping:
            return index, mapping
    return None


def _parse_sheet(sheet, name: str) -> ParsedBoq | None:
    grid = _sheet_grid(sheet)
    found = _find_header(grid)
    if found is None:
        return None
    header_index, mapping = found
    header_row = header_index + 1
    items: list[dict[str, Any]] = []
    warnings: list[str] = []

    def cell(row: list[Any], field: str) -> Any:
        column = mapping.get(field)
        if column is None or column >= len(row):
            return None
        return row[column]

    for offset, row in enumerate(grid[header_index + 1 :], start=header_row + 1):
        if not any(_text(value) for value in row):
            continue
        raw_name = _text(cell(row, "name"))
        if not raw_name:
            continue
        # A repeated header row (page break in the printed sheet) is not an item.
        if _field_of(cell(row, "name")) == "name" and any(
            _field_of(cell(row, field)) == field for field in ("spec", "unit", "qty")
        ):
            continue
        qty, ok = parse_qty(cell(row, "qty"))
        if not ok:
            raw_qty = _text(cell(row, "qty"))
            warnings.append(f"{name} 第 {offset} 行数量无法识别：{raw_qty}")
        seq = _text(cell(row, "seq")) or str(offset)
        items.append(
            {
                "row": offset,
                "seq": seq,
                "name": raw_name,
                "spec": _text(cell(row, "spec")),
                "unit": _text(cell(row, "unit")),
                "qty": qty,
                "note": _text(cell(row, "note")),
            }
        )
    return ParsedBoq(sheet=name, header_row=header_row, items=items, warnings=warnings)


def parse_boq(path: str | Path, sheet: str | None = None) -> ParsedBoq:
    """Parse a BOQ workbook. Raises ``ValueError`` with an actionable message."""
    source = Path(path)
    if not source.is_file():
        raise ValueError(f"文件不存在：{source.name}")
    if source.suffix.lower() not in {".xlsx", ".xlsm"}:
        raise ValueError("工程量清单只支持 .xlsx / .xlsm 格式，请另存为 Excel 工作簿后重试")
    try:
        from openpyxl import load_workbook
    except ImportError as exc:  # pragma: no cover - openpyxl is a hard dependency
        raise ValueError("读取 Excel 需要 openpyxl，请先安装项目依赖") from exc
    try:
        workbook = load_workbook(str(source), data_only=True, read_only=False)
    except Exception as exc:
        logger.warning("无法读取 Excel 文件 %s", source.name, exc_info=True)
        raise ValueError(f"无法读取 Excel 文件（{source.name}）：{exc}") from exc

    names = list(workbook.sheetnames)
    if sheet:
        if sheet not in names:
            raise ValueError(f"工作表不存在：「{sheet}」。可选工作表：{', '.join(names) or '（无）'}")
        targets = [sheet]
    else:
        targets = names

    best: ParsedBoq | None = None
    for name in targets:
        try:
            parsed = _parse_sheet(workbook[name], name)
        except Exception as exc:
            logger.warning("工作表「%s」读取失败", name, exc_info=True)
            raise ValueError(f"工作表「{name}」读取失败：{exc}") from exc
        if parsed is None or not parsed.items:
            continue
        if best is None or len(parsed.items) > len(best.items):
            best = parsed

    if best is None:
        columns = "名称、规格型号、单位、数量"
        if sheet:
            raise ValueError(
                f"工作表「{sheet}」未识别到工程量清单：请确认表头包含 {columns} 中至少两列"
            )
        raise ValueError(
            f"未在 Excel 中找到工程量清单：请确认首个工作表的前 {HEADER_SCAN_ROWS} 行内"
            f"有表头，且包含 {columns} 中至少两列"
        )
    return best


# -------------------------------------------------------------------- matcher

MATCH_THRESHOLD = 0.75
_CONTAINMENT_MIN = 4
_FUZZY_MIN = 0.78
_PUNCT = "（）()【】[]，,。.;；:：、“”\"'《》<>~-—/\\|·`!！?？*#&+ \t\r\n"


def normalize(value: Any) -> str:
    """NFKC, lowercase, drop whitespace and the punctuation set in the contract."""
    text = unicodedata.normalize("NFKC", str(value or "")).lower()
    return "".join(ch for ch in text if ch not in _PUNCT and not ch.isspace())


def _spec_compatible(boq_spec: str, ledger_spec: str) -> bool:
    if not boq_spec or not ledger_spec:
        return True
    return boq_spec in ledger_spec or ledger_spec in boq_spec


def match_score(item: dict[str, Any], material: Material) -> float:
    bname = normalize(item.get("name", ""))
    lname = normalize(material.name)
    if not bname or not lname:
        return 0.0
    bspec = normalize(item.get("spec", ""))
    lspec = normalize(material.spec)
    if bname == lname and bspec == lspec:
        return 1.0
    if bname == lname:
        return 0.90 + (0.05 if _spec_compatible(bspec, lspec) else 0.0)
    if min(len(bname), len(lname)) >= _CONTAINMENT_MIN and (
        bname in lname or lname in bname
    ):
        return 0.82
    ratio = difflib.SequenceMatcher(None, bname, lname).ratio()
    if ratio >= _FUZZY_MIN:
        return round(ratio * 0.90, 4)
    return 0.0


def _assign(items: list[dict[str, Any]], materials: list[Material]) -> dict[int, tuple[int, float]]:
    """Greedy one-to-one assignment: item index -> (material index, score)."""
    candidates: list[tuple[float, int, int]] = []
    for item_index, item in enumerate(items):
        for material_index, material in enumerate(materials):
            score = match_score(item, material)
            if score >= MATCH_THRESHOLD:
                candidates.append((-score, item_index, material_index))
    candidates.sort()
    assigned: dict[int, tuple[int, float]] = {}
    used: set[int] = set()
    for negative, item_index, material_index in candidates:
        if item_index in assigned or material_index in used:
            continue
        assigned[item_index] = (material_index, -negative)
        used.add(material_index)
    return assigned


def _qty_tolerance(boq_qty: float, ledger_qty: float) -> float:
    # Piece counts must match exactly: an off-by-one panel is a real discrepancy.
    # Measured lengths/areas keep a 0.5% tolerance for rounding and unit conversion.
    if float(boq_qty).is_integer() and float(ledger_qty).is_integer():
        return 0.001
    return max(0.001, 0.005 * max(abs(boq_qty), abs(ledger_qty)))


def _classify(item: dict[str, Any], material: Material) -> tuple[str, dict[str, Any]]:
    diff: dict[str, Any] = {"qty": None, "unit": None, "spec": None}
    boq_qty = item.get("qty")
    ledger_qty = material.qty
    qty_diff = False
    if boq_qty is not None and ledger_qty is not None:
        delta = round(float(boq_qty) - float(ledger_qty), 6)
        if abs(delta) > _qty_tolerance(float(boq_qty), float(ledger_qty)):
            qty_diff = True
            diff["qty"] = {"boq": boq_qty, "ledger": ledger_qty, "delta": delta}
    boq_unit = _text(item.get("unit"))
    ledger_unit = _text(material.unit)
    unit_diff = bool(boq_unit and ledger_unit and normalize(boq_unit) != normalize(ledger_unit))
    if unit_diff:
        diff["unit"] = {"boq": boq_unit, "ledger": ledger_unit}
    boq_spec = _text(item.get("spec"))
    ledger_spec = _text(material.spec)
    spec_diff = bool(
        boq_spec and ledger_spec and normalize(boq_spec) != normalize(ledger_spec)
    )
    if spec_diff:
        diff["spec"] = {"boq": boq_spec, "ledger": ledger_spec}
    if qty_diff:
        return "qty_diff", diff
    if unit_diff:
        return "unit_diff", diff
    if spec_diff:
        return "spec_diff", diff
    return "matched", diff


def _ledger_payload(material: Material) -> dict[str, Any]:
    return {
        "material_id": material.id,
        "name": material.name,
        "spec": material.spec or "",
        "unit": material.unit or "",
        "qty": material.qty,
        "note": material.note or "",
    }


def _price_payload(item: dict[str, Any], unit_price: Any) -> dict[str, Any] | None:
    """Return the per-row quote values; amount is derived from BOQ quantity."""
    if unit_price is None:
        return None
    try:
        price = float(unit_price)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(price) or price < 0:
        return None
    qty = item.get("qty")
    amount = round(float(qty) * price, 2) if qty is not None else None
    return {"unit_price": round(price, 4), "amount": amount}


def _row(
    item: dict[str, Any],
    material: Material | None,
    score: float,
    ignored: set[str],
    sheet: str,
    prices: dict[str, Any] | None = None,
) -> dict[str, Any]:
    key = f"{sheet}!{item['row']}"
    price = _price_payload(item, (prices or {}).get(key))
    if material is None:
        return {
            "key": key,
            "boq_row": item["row"],
            "seq": item.get("seq", ""),
            "name": item.get("name", ""),
            "spec": item.get("spec", ""),
            "unit": item.get("unit", ""),
            "qty": item.get("qty"),
            "note": item.get("note", ""),
            "status": "missing_in_ledger",
            "ignored": key in ignored,
            "match_score": 0.0,
            "ledger": None,
            "diff": {"qty": None, "unit": None, "spec": None},
            "price": price,
        }
    status, diff = _classify(item, material)
    return {
        "key": key,
        "boq_row": item["row"],
        "seq": item.get("seq", ""),
        "name": item.get("name", ""),
        "spec": item.get("spec", ""),
        "unit": item.get("unit", ""),
        "qty": item.get("qty"),
        "note": item.get("note", ""),
        "status": status,
        "ignored": key in ignored,
        "match_score": round(float(score), 4),
        "ledger": _ledger_payload(material),
        "diff": diff,
        "price": price,
    }


def _ledger_only_row(material: Material, ignored: set[str]) -> dict[str, Any]:
    key = f"ledger:{material.id}"
    return {
        "key": key,
        "boq_row": None,
        "seq": "",
        "name": material.name,
        "spec": "",
        "unit": "",
        "qty": None,
        "note": "",
        "status": "missing_in_boq",
        "ignored": key in ignored,
        "match_score": 0.0,
        "ledger": _ledger_payload(material),
        "diff": {"qty": None, "unit": None, "spec": None},
        "price": None,
    }


EMPTY_SUMMARY: dict[str, Any] = {
    "boq_rows": 0,
    "adjusted_total": None,
    "matched": 0,
    "qty_diff": 0,
    "unit_diff": 0,
    "spec_diff": 0,
    "missing_in_ledger": 0,
    "missing_in_boq": 0,
    "ignored": 0,
    "total_diffs": 0,
    "match_rate": 0.0,
    "priced": 0,
    "unpriced": 0,
    "quantity_missing": 0,
    "total_amount": 0.0,
    "tax_amount": 0.0,
    "total_with_tax": 0.0,
    "cny_total_with_tax": 0.0,
}


def _summarize(rows: list[dict[str, Any]], boq_rows: int) -> dict[str, Any]:
    summary = dict(EMPTY_SUMMARY)
    summary["boq_rows"] = boq_rows
    for row in rows:
        status = row["status"]
        if status in summary:
            summary[status] += 1
        if row["ignored"]:
            summary["ignored"] += 1
        if row["boq_row"] is None or row["ignored"]:
            continue
        price = row.get("price")
        if not isinstance(price, dict):
            summary["unpriced"] += 1
            continue
        summary["priced"] += 1
        if price.get("amount") is None:
            summary["quantity_missing"] += 1
        else:
            summary["total_amount"] += float(price["amount"])
    summary["total_diffs"] = summary["qty_diff"] + summary["unit_diff"] + summary["spec_diff"]
    summary["total_amount"] = round(summary["total_amount"], 2)
    matched = summary["matched"] + summary["total_diffs"]
    summary["match_rate"] = round(matched / boq_rows, 3) if boq_rows else 0.0
    return summary


def align(
    items: list[dict[str, Any]],
    materials: list[Material],
    ignored: list[str],
    sheet: str,
    prices: dict[str, Any] | None = None,
) -> list[dict[str, Any]]:
    """Align BOQ items with live ledger materials (recomputed on every request)."""
    ignored_keys = set(ignored or [])
    assigned = _assign(items, materials)
    rows: list[dict[str, Any]] = []
    for index, item in enumerate(items):
        pair = assigned.get(index)
        if pair is None:
            rows.append(_row(item, None, 0.0, ignored_keys, sheet, prices))
        else:
            material_index, score = pair
            rows.append(
                _row(item, materials[material_index], score, ignored_keys, sheet, prices)
            )
    used = {material_index for material_index, _ in assigned.values()}
    for index, material in enumerate(materials):
        if index in used:
            continue
        rows.append(_ledger_only_row(material, ignored_keys))
    return rows


