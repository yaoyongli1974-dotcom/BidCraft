def _int_value(value: Any) -> int:
    try:
        return int(value or 0)
    except (TypeError, ValueError):
        return 0


def _stage_min_amount(value: Any) -> int | float | None:
    """Return a valid stage amount threshold (finite number ≥0), else None.

    Booleans, strings, negatives and non-finite numbers are invalid: the key
    is dropped so the stage stays unconditionally applicable (R21).
    """
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    if not math.isfinite(value) or value < 0:
        return None
    return value


STAGE_CONDITION_MAX_ITEMS = 20
STAGE_CONDITION_ITEM_MAX = 40
STAGE_RULE_MAX_ITEMS = 20
STAGE_RULE_VALUE_MAX_ITEMS = 20
STAGE_RULE_STRING_MAX = 40
STAGE_RULE_NUMERIC_FIELDS = (
    "total_amount",
    "boq_rows",
    "priced",
    "unpriced",
    "match_rate",
)
STAGE_RULE_STRING_FIELDS = ("package_id", "currency")
STAGE_RULE_FIELDS = STAGE_RULE_NUMERIC_FIELDS + STAGE_RULE_STRING_FIELDS
STAGE_RULE_OPS = ("gte", "lte", "eq", "ne", "in", "not_in", "contains")


def _stage_str_list(value: Any) -> list[str] | None:
    """Return a clean ``list[str]`` condition list, else None (R25).

    A valid list holds non-empty strings of ≤40 chars; it is trimmed, deduped
    and order-preserving. Non-lists, lists without a single valid item and
    empty lists are invalid: the key is dropped so the stage stays
    unrestricted (mirroring the ``min_amount`` handling).
    """
    if not isinstance(value, list):
        return None
    seen: set[str] = set()
    ordered: list[str] = []
    for item in value:
        if not isinstance(item, str):
            continue
        text = item.strip()
        if not text or len(text) > STAGE_CONDITION_ITEM_MAX or text in seen:
            continue
        seen.add(text)
        ordered.append(text)
    return ordered or None


def _currency_code(value: Any) -> str:
    """Normalize a currency code for white-list comparison (R25)."""
    if not isinstance(value, str):
        return ""
    return value.strip().upper()


def _stage_number(value: Any) -> int | float | None:
    """Finite number used by numeric rule operands; booleans are invalid."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    if not math.isfinite(value):
        return None
    return value


def _stage_rule_value(field_name: str, op: str, value: Any) -> Any:
    """Normalize one rule operand for ``field_name``/``op``; None means invalid."""
    if op in ("in", "not_in"):
        return _stage_str_list(value)
    if field_name in STAGE_RULE_NUMERIC_FIELDS:
        return _stage_number(value)
    text = str(value or "").strip()
    if not text or len(text) > STAGE_RULE_STRING_MAX:
        return None
    return _currency_code(text) if field_name == "currency" else text


def _stage_rules(value: Any) -> list[dict[str, Any]]:
    """Normalize optional per-stage rule conditions; invalid entries are dropped.

    Rules are additional AND conditions on the already-supported approval
    context (``total_amount``/``package_id``/``currency`` and, on BOQ paths,
    quote-summary metrics). They are opt-in:
    a stage without valid rules keeps its previous unconditional behaviour.
    """
    if not isinstance(value, list):
        return []
    rules: list[dict[str, Any]] = []
    for entry in value[:STAGE_RULE_MAX_ITEMS]:
        if not isinstance(entry, dict):
            continue
        field_name = str(entry.get("field") or "").strip()
        op = str(entry.get("op") or "").strip()
        if field_name not in STAGE_RULE_FIELDS or op not in STAGE_RULE_OPS:
            continue
        operand = _stage_rule_value(field_name, op, entry.get("value"))
        if operand is None:
            continue
        rules.append({"field": field_name, "op": op, "value": operand})
    return rules


def _rule_value_matches(field_name: str, actual: Any, op: str, expected: Any) -> bool:
    """Evaluate one normalized rule; unknown actual values stay conservative."""
    if op in ("in", "not_in"):
        if not isinstance(actual, str) or not actual.strip():
            return True
        left = _currency_code(actual) if field_name == "currency" else actual.strip()
        present = left in expected
        return present if op == "in" else not present
    if op in ("gte", "lte"):
        number = _stage_number(actual)
        if number is None:
            return True
        return number >= expected if op == "gte" else number <= expected
    if actual is None:
        return True
    left = _currency_code(actual) if field_name == "currency" else str(actual).strip()
    right = expected if isinstance(expected, str) else str(expected)
    if op == "contains":
        return right.lower() in left.lower()
    return left == right if op == "eq" else left != right


def _attach_stage_conditions(stage: dict[str, Any], entry: dict[str, Any]) -> None:
    """Copy the valid R21/R25 condition keys of ``entry`` onto ``stage``."""
    threshold = _stage_min_amount(entry.get("min_amount"))
    if threshold is not None:
        stage["min_amount"] = threshold
    for key in ("packages", "currencies"):
        values = _stage_str_list(entry.get(key))
        if values is not None:
            stage[key] = values
    rules = _stage_rules(entry.get("rules"))
    if rules:
        stage["rules"] = rules


def normalize_chain(raw: Any) -> list[dict[str, Any]]:
    """Normalize a stored approval chain into the R19 v2 stage format.

    R18 flat entries ``{id, name}`` become single-approver ``all`` stages;
    v2 stages ``{approvers: [{id, name}], mode}`` are kept as-is with a
    missing/invalid ``mode`` falling back to ``all``. A valid optional
    ``min_amount`` (R21 amount threshold, finite number ≥0) is preserved;
    invalid values drop the key. R25 adds the same treatment for the
    ``packages`` / ``currencies`` white-lists (non-empty ``list[str]``, items
    deduped in order and ≤40 chars). v0.32.1 adds optional ``rules``: up to 20
    AND conditions per stage, each ``{field, op, value}`` over
    ``total_amount`` / ``package_id`` / ``currency``, plus quote-summary metrics
    ``boq_rows`` / ``priced`` / ``unpriced`` / ``match_rate`` on BOQ paths.
    Invalid rules are dropped
    so a stage without valid conditions stays unconditional. Malformed entries
    are ignored so legacy or hand-edited meta never breaks review.
    """
    stages: list[dict[str, Any]] = []
    for entry in list(raw or []):
        if not isinstance(entry, dict):
            continue
        if "approvers" in entry:
            approvers: list[dict[str, str]] = []
            for person in list(entry.get("approvers") or []):
                if not isinstance(person, dict):
                    continue
                user_id = str(person.get("id") or "").strip()
                if not user_id:
                    continue
                approvers.append({"id": user_id, "name": str(person.get("name") or "")})
            if not approvers:
                continue
            mode = entry.get("mode")
            if mode not in ("all", "any"):
                mode = "all"
            stage: dict[str, Any] = {"approvers": approvers, "mode": mode}
            _attach_stage_conditions(stage, entry)
            stages.append(stage)
        else:
            user_id = str(entry.get("id") or "").strip()
            if not user_id:
                continue
            stage = {
                "approvers": [{"id": user_id, "name": str(entry.get("name") or "")}],
                "mode": "all",
            }
            _attach_stage_conditions(stage, entry)
            stages.append(stage)
    return stages


def _stage_explain(
    stage: dict[str, Any],
    total_amount: Any,
    package_id: Any,
    currency: Any,
    *,
    amount_known: bool,
    summary: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Explain why one stage is (or is not) applicable (v0.33.0 RC-09).

    Single source of truth for stage applicability: ``_stage_applies`` simply
    returns ``applicable``. Every condition carries ``field`` / ``op`` /
    ``value`` / ``actual`` / ``hit`` / ``missing``; ``missing_data`` lists the
    field names whose actual value was unknown. Unknown values stay on the
    conservative side of the existing evaluation (over-review, not missed
    approval): amount gates and rules are satisfied while white-lists skip
    the stage, exactly as before.
    """

    conditions: list[dict[str, Any]] = []
    missing_data: list[str] = []

    def add_condition(
        field_name: str, op: str, value: Any, actual: Any, hit: bool, missing: bool
    ) -> None:
        conditions.append(
            {
                "field": field_name,
                "op": op,
                "value": value,
                "actual": actual,
                "hit": bool(hit),
                "missing": bool(missing),
            }
        )
        if missing:
            missing_data.append(field_name)

    threshold = _stage_min_amount(stage.get("min_amount"))
    if threshold is not None:
        hit = not (amount_known and total_amount < threshold)
        add_condition(
            "min_amount",
            "gte",
            threshold,
            total_amount if amount_known else None,
            hit,
            not amount_known,
        )

    packages = _stage_str_list(stage.get("packages"))
    if packages is not None:
        package = str(package_id or "").strip()
        add_condition(
            "package_id", "in", packages, package or None, bool(package and package in packages), not package
        )

    currencies = _stage_str_list(stage.get("currencies"))
    if currencies is not None:
        code = _currency_code(currency)
        codes = [_currency_code(item) for item in currencies]
        add_condition(
            "currency", "in", codes, code or None, bool(code and code in codes), not code
        )

    context: dict[str, Any] = {
        "total_amount": total_amount,
        "package_id": package_id,
        "currency": currency,
    }
    # Quote-only summary metrics are available for BOQ version review and for
    # commercial approvals that thread their stored quote as the summary.
    for field_name in STAGE_RULE_NUMERIC_FIELDS:
        if field_name != "total_amount":
            context[field_name] = _stage_number((summary or {}).get(field_name))
    for rule in _stage_rules(stage.get("rules")):
        actual = context.get(rule["field"])
        hit = _rule_value_matches(rule["field"], actual, rule["op"], rule["value"])
        missing = actual is None or (
            isinstance(actual, str) and not actual.strip()
        )
        add_condition(rule["field"], rule["op"], rule["value"], actual, hit, missing)

    return {
        "applicable": all(condition["hit"] for condition in conditions),
        "conditions": conditions,
        "missing_data": missing_data,
    }


def empty_chain_explain() -> dict[str, Any]:
    """Explain the implicit owner-only approval used when no chain exists.

    No approver identity is invented: the chain is empty, so the only authoritative
    rule is the project owner. Kept as a shared helper so BOQ and commercial
    pending inboxes present exactly the same explanation.
    """

    return {
        "index": 1,
        "applicable": True,
        "conditions": [],
        "missing_data": [],
        "owner_only": True,
        "note": "未配置审批链，由项目 owner 审批",
    }


def _stage_applies(
    stage: dict[str, Any],
    total_amount: Any,
    package_id: Any,
    currency: Any,
    *,
    amount_known: bool,
    summary: dict[str, Any] | None = None,
) -> bool:
    """Whether one stage is applicable under all of its conditions (R21/R25).

    Delegates to :func:`_stage_explain` so filtering and explanation can never
    diverge; see that function for the conservative unknown-value semantics.
    """

    return _stage_explain(
        stage,
        total_amount,
        package_id,
        currency,
        amount_known=amount_known,
        summary=summary,
    )["applicable"]


def _chain_explain(
    chain: list[dict[str, Any]],
    total_amount: Any,
    package_id: Any,
    currency: Any,
    summary: dict[str, Any] | None = None,
) -> list[dict[str, Any]]:
    """Per-stage explanations aligned with the original chain order."""

    known = (
        isinstance(total_amount, (int, float))
        and not isinstance(total_amount, bool)
        and math.isfinite(total_amount)
    )
    return [
        {
            "index": index,
            **_stage_explain(
                stage,
                total_amount,
                package_id,
                currency,
                amount_known=known,
                summary=summary,
            ),
        }
        for index, stage in enumerate(chain)
    ]


def applicable_stages(
    chain: list[dict[str, Any]],
    total_amount: Any = None,
    package_id: Any = None,
    currency: Any = None,
    summary: dict[str, Any] | None = None,
) -> list[tuple[int, dict[str, Any]]]:
    """Filter the chain to the stages taking effect for a version (R21/R25).

    A stage carrying ``min_amount`` only applies once the version total reaches
    it (``total_amount >= min_amount``); stages without a threshold always
    apply. An unknown total (None / missing / non-numeric) keeps the amount
    condition satisfied — conservative, better over-review than miss one.
    ``packages`` / ``currencies`` white-lists need ``package_id`` / the
    normalized ``currency`` to be a member; an unknown context skips such a
    stage. Optional ``rules`` are evaluated with the same context plus a
    supplied quote ``summary`` (numeric BOQ metrics) and ANDed.
    When the conditions filter out every stage the full chain is used
    instead, so a conditional chain never ends up with zero approval levels.
    Returns ``(original chain index, stage)`` pairs in chain order.
    """
    known = (
        isinstance(total_amount, (int, float))
        and not isinstance(total_amount, bool)
        and math.isfinite(total_amount)
    )
    stages: list[tuple[int, dict[str, Any]]] = []
    for index, stage in enumerate(chain):
        if _stage_applies(
            stage,
            total_amount,
            package_id,
            currency,
            amount_known=known,
            summary=summary,
        ):
            stages.append((index, stage))
    if chain and not stages:
        return list(enumerate(chain))
    return stages


def completed_stages(
    chain: list[dict[str, Any]],
    approvals: list[dict],
    total_amount: Any = None,
    package_id: Any = None,
    currency: Any = None,
    summary: dict[str, Any] | None = None,
) -> int:
    """Count leading fully signed-off applicable stages (R19 all/any, R21/R25).

    Only stages applicable to the version context (``total_amount``,
    ``package_id``, ``currency``) are walked; inapplicable stages are skipped
    without counting or stopping the scan. A stage is complete when its
    approve-record count (records keep the original chain index) reaches ``1``
    (any) or ``len(approvers)`` (all); the scan stops at the first incomplete
    applicable stage, so the result is also the ordinal of the current pending
    applicable level. Omitting the context treats every stage as applicable,
    preserving the pre-R21 two-argument behavior.
    """
    completed = 0
    for index, stage in applicable_stages(
        chain, total_amount, package_id, currency, summary
    ):
        approvers = stage.get("approvers") or []
        count = len(
            [
                r
                for r in approvals
                if r.get("decision") == "approve" and r.get("stage") == index
            ]
        )
        needed = 1 if stage.get("mode") == "any" else len(approvers)
        if needed > 0 and count >= needed:
            completed += 1
        else:
            break
    return completed


def version_currency(
    version: BoqQuoteVersion, project: Project | None = None
) -> str | None:
    """Approval-gate currency of one version: immutable basis first, policy fallback.

    A version freezes ``basis.currency`` at save time, so a USD version must not
    silently fall into the default CNY approval branch. An explicit, non-default
    currency policy change *after* the version was frozen is the one exception:
    it deliberately re-scopes pending approvals (R25 policy-switch contract).
    """

    frozen = _text((version.basis or {}).get("currency"))
    if project is None:
        return frozen or None
    policy = get_price_policy(project)
    revision = _int_value((project.meta or {}).get(POLICY_CURRENCY_REVISION_KEY))
    frozen_revision = _int_value((version.basis or {}).get("currency_revision"))
    default = _currency_code(DEFAULT_PRICE_POLICY["currency"])
    if frozen and (revision <= frozen_revision or _currency_code(policy["currency"]) == default):
        return frozen
    return policy["currency"]


def version_payload(
    version: BoqQuoteVersion,
    *,
    include_prices: bool = False,
    project: Project | None = None,
) -> dict[str, Any]:
    """Serialize one quote version; the detail payload additionally carries prices.

    ``project`` (when given) supplies the approval chain so ``approval_stage``
    can report the pending applicable level of a submitted version and
    ``approval_stage_count`` the number of stages applicable to the version
    context (``summary.total_amount`` plus the version's package and the
    project currency — R21 amount thresholds, R25 package/currency gates;
    unknown total → all).
    """
    prices = dict(version.prices or {})
    approvals = list(version.approvals or [])
    summary = dict(version.summary or {})
    chain = normalize_chain((project.meta or {}).get("approval_chain")) if project else []
    total_amount = summary.get("total_amount")
    package_id = version.package_id
    currency = version_currency(version, project)
    payload: dict[str, Any] = {
        "id": version.id,
        "name": version.name,
        "note": version.note or "",
        "package_id": version.package_id,
        "summary": summary,
        "basis": dict(version.basis or {}),
        "created_at": clock.iso_utc(version.created_at),
        "price_count": len(prices),
        "status": version.status or "draft",
        "submit_note": version.submit_note or "",
        "submitted_by": version.submitted_by or "",
        "submitted_at": clock.iso_utc(version.submitted_at),
        "review_note": version.review_note or "",
        "reviewed_by": version.reviewed_by or "",
        "reviewed_at": clock.iso_utc(version.reviewed_at),
        "approvals": approvals,
        "approval_stage": (
            completed_stages(
                chain, approvals, total_amount, package_id, currency, summary
            )
            if (version.status or "draft") == "submitted" and chain
            else 0
        ),
        "approval_stage_count": len(
            applicable_stages(chain, total_amount, package_id, currency, summary)
        ),
        # v0.33.0 RC-09：逐条件命中 / 缺失说明，与生效级判定同源。
        "approval_explain": _chain_explain(
            chain, total_amount, package_id, currency, summary
        ),
    }
    if include_prices:
        payload["prices"] = prices
    return payload


def _version_statement(project_id: str, package_id: str | None):
    statement = select(BoqQuoteVersion).where(BoqQuoteVersion.project_id == project_id)
    if package_id is None:
        statement = statement.where(BoqQuoteVersion.package_id.is_(None))
    else:
        statement = statement.where(BoqQuoteVersion.package_id == package_id)
    return statement


def count_versions(db: Session, project_id: str, package_id: str | None = None) -> int:
    statement = select(func.count()).select_from(BoqQuoteVersion).where(
        BoqQuoteVersion.project_id == project_id
    )
    if package_id is None:
        statement = statement.where(BoqQuoteVersion.package_id.is_(None))
    else:
        statement = statement.where(BoqQuoteVersion.package_id == package_id)
    return int(db.scalar(statement) or 0)


def list_versions(
    db: Session, project: Project, package_id: str | None = None
) -> list[dict[str, Any]]:
    """List saved versions of one package, newest first (without prices)."""
    package = resolve_package(db, project, package_id)
    resolved = package.id if package else None
    rows = db.scalars(
        _version_statement(project.id, resolved).order_by(
            BoqQuoteVersion.created_at.desc(), BoqQuoteVersion.id.desc()
        )
    )
    return [version_payload(row, project=project) for row in rows]


def get_version(
    db: Session, project_id: str, version_id: str
) -> BoqQuoteVersion | None:
    version = db.get(BoqQuoteVersion, version_id)
    if version is None or version.project_id != project_id:
        return None
    return version


def save_version(
    db: Session,
    project: Project,
    name: str,
    note: str = "",
    package_id: str | None = None,
) -> dict[str, Any]:
    """Freeze the package's current prices and summary as a new version."""
    clean_name = (name or "").strip()
    if not clean_name:
        raise ValueError("版本名称不能为空")
    if len(clean_name) > QUOTE_VERSION_NAME_MAX:
        raise ValueError(f"版本名称不能超过 {QUOTE_VERSION_NAME_MAX} 个字符")
    package = resolve_package(db, project, package_id)
    resolved = package.id if package else None
    snapshot = get_snapshot(db, project.id, resolved)
    if snapshot is None:
        raise BoqConflictError("尚未上传工程量清单，请先导入清单文件")
    if count_versions(db, project.id, resolved) >= MAX_QUOTE_VERSIONS:
        raise BoqConflictError(f"版本数已达上限（{MAX_QUOTE_VERSIONS}）")
    payload = build_payload(db, project.id, resolved)
    # 不可变计算依据：单价存 prices，这里冻结数量、税率、币种、汇率、系数与
    # 舍入位，供审计与复算；save 之后项目策略再改也不影响这份快照。
    qty_by_key = {
        f"{snapshot.sheet}!{row.get('row')}": row.get("qty")
        for row in (snapshot.items or [])
        if row.get("qty") is not None
    }
    policy = get_price_policy(project)
    basis = {
        "qty": qty_by_key,
        "tax_rate": policy["tax_rate"],
        "currency": policy["currency"],
        "currency_revision": _int_value(
            (project.meta or {}).get(POLICY_CURRENCY_REVISION_KEY)
        ),
        "exchange_rate": policy["exchange_rate"],
        "factor": policy["factor"],
        "round_digits": policy["round_digits"],
    }
    version = BoqQuoteVersion(
        project_id=project.id,
        package_id=resolved,
        name=clean_name,
        note=(note or "").strip()[:QUOTE_VERSION_NOTE_MAX],
        prices=dict(snapshot.prices or {}),
        summary=dict(payload.get("summary") or {}),
        basis=basis,
    )
    db.add(version)
    db.flush()
    return version_payload(version, project=project)


