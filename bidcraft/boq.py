def version_payload(version: BoqQuoteVersion, *, include_prices: bool = False) -> dict[str, Any]:
    """Serialize one quote version; the detail payload additionally carries prices."""
    prices = dict(version.prices or {})
    payload: dict[str, Any] = {
        "id": version.id,
        "name": version.name,
        "note": version.note or "",
        "package_id": version.package_id,
        "summary": dict(version.summary or {}),
        "created_at": version.created_at.isoformat() if version.created_at else None,
        "price_count": len(prices),
        "status": version.status or "draft",
        "submit_note": version.submit_note or "",
        "submitted_by": version.submitted_by or "",
        "submitted_at": (
            version.submitted_at.isoformat() if version.submitted_at else None
        ),
        "review_note": version.review_note or "",
        "reviewed_by": version.reviewed_by or "",
        "reviewed_at": version.reviewed_at.isoformat() if version.reviewed_at else None,
    }
    if include_prices:
        payload["prices"] = prices
    return payload


def _version_statement(project_id: str, package_id: str | None):
    statement = select(BoqQuoteVersion).where(BoqQuoteVersion.project_id == project_id)
    if package_id is None:
        statement = statement.where(BoqQuoteVersion.package_id.is_(None))
    else:
        statement = statement.where(BoqQuoteVersion.package_id == package_id)
    return statement


def count_versions(db: Session, project_id: str, package_id: str | None = None) -> int:
    statement = select(func.count()).select_from(BoqQuoteVersion).where(
        BoqQuoteVersion.project_id == project_id
    )
    if package_id is None:
        statement = statement.where(BoqQuoteVersion.package_id.is_(None))
    else:
        statement = statement.where(BoqQuoteVersion.package_id == package_id)
    return int(db.scalar(statement) or 0)


def list_versions(
    db: Session, project: Project, package_id: str | None = None
) -> list[dict[str, Any]]:
    """List saved versions of one package, newest first (without prices)."""
    package = resolve_package(db, project, package_id)
    resolved = package.id if package else None
    rows = db.scalars(
        _version_statement(project.id, resolved).order_by(
            BoqQuoteVersion.created_at.desc(), BoqQuoteVersion.id.desc()
        )
    )
    return [version_payload(row) for row in rows]


def get_version(
    db: Session, project_id: str, version_id: str
) -> BoqQuoteVersion | None:
    version = db.get(BoqQuoteVersion, version_id)
    if version is None or version.project_id != project_id:
        return None
    return version


def save_version(
    db: Session,
    project: Project,
    name: str,
    note: str = "",
    package_id: str | None = None,
) -> dict[str, Any]:
    """Freeze the package's current prices and summary as a new version."""
    clean_name = (name or "").strip()
    if not clean_name:
        raise ValueError("版本名称不能为空")
    if len(clean_name) > QUOTE_VERSION_NAME_MAX:
        raise ValueError(f"版本名称不能超过 {QUOTE_VERSION_NAME_MAX} 个字符")
    package = resolve_package(db, project, package_id)
    resolved = package.id if package else None
    snapshot = get_snapshot(db, project.id, resolved)
    if snapshot is None:
        raise BoqConflictError("尚未上传工程量清单，请先导入清单文件")
    if count_versions(db, project.id, resolved) >= MAX_QUOTE_VERSIONS:
        raise BoqConflictError(f"版本数已达上限（{MAX_QUOTE_VERSIONS}）")
    payload = build_payload(db, project.id, resolved)
    version = BoqQuoteVersion(
        project_id=project.id,
        package_id=resolved,
        name=clean_name,
        note=(note or "").strip()[:QUOTE_VERSION_NOTE_MAX],
        prices=dict(snapshot.prices or {}),
        summary=dict(payload.get("summary") or {}),
    )
    db.add(version)
    db.flush()
    return version_payload(version)


def restore_version(
    db: Session, project: Project, version_id: str
) -> dict[str, Any]:
    """Write one version's prices back onto its package's active snapshot."""
    version = get_version(db, project.id, version_id)
    if version is None:
        raise LookupError("版本不存在")
    snapshot = get_snapshot(db, project.id, version.package_id)
    if snapshot is None:
        raise BoqConflictError("尚未上传工程量清单，请先导入清单文件")
    snapshot.prices = dict(version.prices or {})
    db.flush()
    return build_payload(db, project.id, version.package_id)


def delete_version(db: Session, project: Project, version_id: str) -> None:
    version = get_version(db, project.id, version_id)
    if version is None:
        raise LookupError("版本不存在")
    db.delete(version)
    db.flush()


def _clean_actor(actor: str | None) -> str:
    return (actor or "").strip()[:80]


def _clean_note(note: str | None) -> str:
    return (note or "").strip()[:QUOTE_VERSION_NOTE_MAX]


def submit_version(
    db: Session,
    project: Project,
    version_id: str,
    *,
    actor: str = "",
    note: str = "",
) -> dict[str, Any]:
    """Send a draft (or rejected) version to the reviewer: draft|rejected → submitted."""
    version = get_version(db, project.id, version_id)
    if version is None:
        raise LookupError("版本不存在")
    if (version.status or "draft") not in {"draft", "rejected"}:
        raise BoqConflictError("当前状态不可提交审批")
    version.status = "submitted"
    version.submit_note = _clean_note(note)
    version.submitted_by = _clean_actor(actor)
    version.submitted_at = utcnow()
    # A resubmission starts a new review round; previous review feedback is void.
    version.review_note = ""
    version.reviewed_by = ""
    version.reviewed_at = None
    db.flush()
    return version_payload(version)


def review_version(
    db: Session,
    project: Project,
    version_id: str,
    *,
    actor: str = "",
    decision: str,
    note: str = "",
) -> dict[str, Any]:
    """Approve or reject a submitted version; approving withdraws the old one."""
    if decision not in QUOTE_REVIEW_DECISIONS:
        raise ValueError("decision 只能是 approve 或 reject")
    version = get_version(db, project.id, version_id)
    if version is None:
        raise LookupError("版本不存在")
    if (version.status or "draft") != "submitted":
        raise BoqConflictError("仅待审版本可审批")
    if decision == "approve":
        # One approved version per package: retire the previous winner to draft
        # without touching its review trail (audit keeps the history).
        others = db.scalars(
            _version_statement(project.id, version.package_id).where(
                BoqQuoteVersion.status == "approved",
                BoqQuoteVersion.id != version.id,
            )
        )
        for other in others:
            other.status = "draft"
        version.status = "approved"
    else:
        version.status = "rejected"
    version.review_note = _clean_note(note)
    version.reviewed_by = _clean_actor(actor)
    version.reviewed_at = utcnow()
    db.flush()
    return version_payload(version)


def unapprove_version(
    db: Session, project: Project, version_id: str
) -> dict[str, Any]:
    """Withdraw an approval: approved → draft."""
    version = get_version(db, project.id, version_id)
    if version is None:
        raise LookupError("版本不存在")
    if (version.status or "draft") != "approved":
        raise BoqConflictError("仅已定稿版本可撤销")
    version.status = "draft"
    db.flush()
    return version_payload(version)


def diff_version(
    db: Session,
    project: Project,
    version_id: str,
    other: str | None = None,
) -> dict[str, Any]:
    """Compare one saved version against the current snapshot or another version."""
    version = get_version(db, project.id, version_id)
    if version is None:
        raise LookupError("版本不存在")
    prices_a = dict(version.prices or {})
    if other in (None, "", "current"):
        snapshot = get_snapshot(db, project.id, version.package_id)
        if snapshot is None:
            raise BoqConflictError("尚未上传工程量清单，请先导入清单文件")
        prices_b = dict(snapshot.prices or {})
        other_id = "current"
        summary_b = dict(
            build_payload(db, project.id, version.package_id).get("summary") or {}
        )
    else:
        counterpart = get_version(db, project.id, other)
        if counterpart is None:
            raise LookupError("对比版本不存在")
        if counterpart.package_id != version.package_id:
            raise LookupError("对比版本不属于同一包件")
        prices_b = dict(counterpart.prices or {})
        other_id = counterpart.id
        summary_b = dict(counterpart.summary or {})
    rows = build_payload(db, project.id, version.package_id).get("rows") or []
    meta = {row["key"]: row for row in rows if row.get("boq_row") is not None}

    def amount(key: str, price: Any) -> float | None:
        qty = (meta.get(key) or {}).get("qty")
        if qty is None or price is None:
            return None
        return round(float(qty) * float(price), 2)

    def entry(key: str, price: Any) -> dict[str, Any]:
        return {
            "key": key,
            "name": (meta.get(key) or {}).get("name", ""),
            "unit_price": price,
            "amount": amount(key, price),
        }

    added = [entry(key, prices_a[key]) for key in sorted(prices_a) if key not in prices_b]
    removed = [
        entry(key, prices_b[key]) for key in sorted(prices_b) if key not in prices_a
    ]
    changed = []
    for key in sorted(prices_a):
        if key in prices_b and prices_a[key] != prices_b[key]:
            changed.append(
                {
                    "key": key,
                    "name": (meta.get(key) or {}).get("name", ""),
                    "from": prices_a[key],
                    "to": prices_b[key],
                    "from_amount": amount(key, prices_a[key]),
                    "to_amount": amount(key, prices_b[key]),
                }
            )
    return {
        "version_id": version.id,
        "other_id": other_id,
        "added": added,
        "removed": removed,
        "changed": changed,
        "summary_a": dict(version.summary or {}),
        "summary_b": summary_b,
        "count_a": len(prices_a),
        "count_b": len(prices_b),
    }


def find_row(rows: list[dict[str, Any]], boq_row: int) -> dict[str, Any] | None:
    for row in rows:
        if row["boq_row"] == boq_row:
            return row
    return None


def set_unit_price(
    db: Session,
    project: Project,
    boq_row: int,
    unit_price: float | None,
    *,
    package_id: str | None = None,
) -> dict[str, Any]:
    """Set or clear the user-entered unit price for one BOQ row."""
    snapshot = get_snapshot(db, project.id, package_id)
    if snapshot is None:
        raise BoqConflictError("尚未上传工程量清单，请先导入清单文件")
    items = list(snapshot.items or [])
    item = next((entry for entry in items if entry.get("row") == boq_row), None)
    if item is None:
        raise LookupError(f"清单行不存在：{boq_row}")

    prices = dict(snapshot.prices or {})
    key = f"{snapshot.sheet}!{boq_row}"
    if unit_price is None:
        prices.pop(key, None)
    else:
        try:
            value = float(unit_price)
        except (TypeError, ValueError) as exc:
            raise ValueError("单价必须是数字") from exc
        if not math.isfinite(value) or value < 0:
            raise ValueError("单价必须是非负有限数字")
        prices[key] = round(value, 4)
    snapshot.prices = prices
    db.flush()
    return build_payload(db, project.id, package_id)


def apply_action(
    db: Session,
    project: Project,
    boq_row: int,
    action: str,
    *,
    package_id: str | None = None,
) -> dict[str, Any]:
    """Apply one reconciliation action and return the recomputed payload."""
    snapshot = get_snapshot(db, project.id, package_id)
    if snapshot is None:
        raise BoqConflictError("尚未上传工程量清单，请先导入清单文件")
    items = list(snapshot.items or [])
    item = next((entry for entry in items if entry.get("row") == boq_row), None)
    if item is None:
        raise LookupError(f"清单行不存在：{boq_row}")

    normalized_action = (action or "").strip().lower()
    key = f"{snapshot.sheet}!{boq_row}"
    ignored = list(snapshot.ignored or [])

    if normalized_action in {"ignore", "restore"}:
        if normalized_action == "ignore":
            if key not in ignored:
                ignored.append(key)
        else:
            ignored = [entry for entry in ignored if entry != key]
        snapshot.ignored = ignored
        db.flush()
        return build_payload(db, project.id, package_id)

    materials = list(
        db.scalars(
            select(Material).where(Material.project_id == project.id).order_by(Material.id)
        )
    )
    rows = align(items, materials, ignored, snapshot.sheet)
    row = find_row(rows, boq_row)

    if normalized_action == "update":
        if row is None or row["status"] == "missing_in_ledger":
            raise BoqConflictError("该清单行未匹配到台账材料，无法更新；可先加入台账")
        material = db.get(Material, row["ledger"]["material_id"])
        if material is None:
            raise BoqConflictError("台账材料已不存在，请重新解析招标文件后再试")
        if item.get("qty") is not None:
            material.qty = item["qty"]
        if _text(item.get("unit")):
            material.unit = _text(item["unit"])
        if _text(item.get("spec")):
            material.spec = _text(item["spec"])
        db.flush()
        return build_payload(db, project.id, package_id)

    if normalized_action == "add":
        if row is not None and row["status"] == "missing_in_boq":
            raise BoqConflictError("该行是台账材料而非清单行，无法加入台账")
        if row is not None and row["ledger"] is not None:
            raise BoqConflictError("该清单行已匹配台账材料；如需覆盖请使用「更新台账」")
        material = Material(
            project_id=project.id,
            name=_text(item.get("name")),
            spec=_text(item.get("spec")),
            unit=_text(item.get("unit")),
            qty=item.get("qty"),
            note=_text(item.get("note")),
            source_quote=f"{snapshot.filename} 第{boq_row}行",
        )
        db.add(material)
        db.flush()
        return build_payload(db, project.id, package_id)

    raise ValueError("action 只能是 update、add、ignore 或 restore")


# -------------------------------------------------------------- price policy

DEFAULT_PRICE_POLICY: dict[str, Any] = {
    "enabled": False,
    "factor": 1.0,
    "round_digits": 2,
    "tax_rate": 0.0,
    "currency": "CNY",
    "exchange_rate": 1.0,
}
FACTOR_MIN = 0.1
FACTOR_MAX = 10.0
ROUND_DIGITS_MIN = 0
ROUND_DIGITS_MAX = 4
TAX_RATE_MIN = 0.0
TAX_RATE_MAX = 0.5
DEFAULT_TAX_RATE = 0.0
EXCHANGE_RATE_MIN = 0.0001
EXCHANGE_RATE_MAX = 10000.0
DEFAULT_EXCHANGE_RATE = 1.0
CURRENCIES = ("CNY", "USD", "EUR", "HKD")
DEFAULT_CURRENCY = "CNY"


def _clamp_factor(value: Any, default: float = 1.0) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return default
    if not math.isfinite(number):
        return default
    return min(max(number, FACTOR_MIN), FACTOR_MAX)


def _clamp_round_digits(value: Any, default: int = 2) -> int:
    if isinstance(value, bool):
        return default
    try:
        number = int(value)
    except (TypeError, ValueError):
        return default
    return min(max(number, ROUND_DIGITS_MIN), ROUND_DIGITS_MAX)


def _clamp_tax_rate(value: Any, default: float = DEFAULT_TAX_RATE) -> float:
    if isinstance(value, bool):
        return default
    try:
        number = float(value)
    except (TypeError, ValueError):
        return default
    if not math.isfinite(number):
        return default
    return min(max(number, TAX_RATE_MIN), TAX_RATE_MAX)


def _normalize_currency(value: Any, default: str = DEFAULT_CURRENCY) -> str:
    if not isinstance(value, str):
        return default
    code = value.strip().upper()
    return code if code in CURRENCIES else default


def _clamp_exchange_rate(
    value: Any, default: float = DEFAULT_EXCHANGE_RATE
) -> float:
    """1 unit of the quote currency = X CNY; clamp to a sane range."""
    if isinstance(value, bool):
        return default
    try:
        number = float(value)
    except (TypeError, ValueError):
        return default
    if not math.isfinite(number):
        return default
    return min(max(number, EXCHANGE_RATE_MIN), EXCHANGE_RATE_MAX)


def _resolve_exchange_rate(currency: str, value: Any, default: float) -> float:
    """CNY is the base currency, so its exchange rate is always exactly 1."""
    if currency == DEFAULT_CURRENCY:
        return DEFAULT_EXCHANGE_RATE
    return _clamp_exchange_rate(value, default)


def get_price_policy(project: Project | None) -> dict[str, Any]:
    """Return the project's price policy with defaults and range clamping."""
    raw = (project.meta or {}).get("price_policy") if project is not None else None
    policy = dict(DEFAULT_PRICE_POLICY)
    if isinstance(raw, dict):
        if "enabled" in raw:
            policy["enabled"] = bool(raw.get("enabled"))
        policy["factor"] = _clamp_factor(raw.get("factor"), policy["factor"])
        policy["round_digits"] = _clamp_round_digits(
            raw.get("round_digits"), policy["round_digits"]
        )
        policy["tax_rate"] = _clamp_tax_rate(raw.get("tax_rate"), policy["tax_rate"])
        policy["currency"] = _normalize_currency(raw.get("currency"), policy["currency"])
        policy["exchange_rate"] = _resolve_exchange_rate(
            policy["currency"], raw.get("exchange_rate"), policy["exchange_rate"]
        )
    return policy


def set_price_policy(
    db: Session, project: Project, updates: dict[str, Any]
) -> dict[str, Any]:
    """Merge arbitrary policy fields, clamp them and persist on ``project.meta``."""
    current = get_price_policy(project)
    candidate = dict(current)
    if "enabled" in updates and updates["enabled"] is not None:
        candidate["enabled"] = bool(updates["enabled"])
    if updates.get("factor") is not None:
        candidate["factor"] = _clamp_factor(updates["factor"], current["factor"])
    if updates.get("round_digits") is not None:
        candidate["round_digits"] = _clamp_round_digits(
            updates["round_digits"], current["round_digits"]
        )
    if updates.get("tax_rate") is not None:
        candidate["tax_rate"] = _clamp_tax_rate(updates["tax_rate"], DEFAULT_TAX_RATE)
    if updates.get("currency") is not None:
        candidate["currency"] = _normalize_currency(updates["currency"], DEFAULT_CURRENCY)
    if updates.get("exchange_rate") is not None:
        candidate["exchange_rate"] = _resolve_exchange_rate(
            candidate["currency"], updates["exchange_rate"], current["exchange_rate"]
        )
    if candidate["currency"] == DEFAULT_CURRENCY:
        candidate["exchange_rate"] = DEFAULT_EXCHANGE_RATE
    meta = dict(project.meta or {})
    meta["price_policy"] = candidate
    project.meta = meta
    db.flush()
    return candidate


def _adjusted_total(summary: dict[str, Any], policy: dict[str, Any]) -> float | None:
    """Adjusted total for display only; quoted rows always keep their prices."""
    if not policy.get("enabled"):
        return None
    total = float(summary.get("total_amount") or 0.0)
    return round(total * float(policy.get("factor", 1.0)), int(policy.get("round_digits", 2)))


def _apply_tax(summary: dict[str, Any], policy: dict[str, Any]) -> dict[str, Any]:
    """Add tax_amount / total_with_tax / cny_total_with_tax.

    The CNY figure converts the tax-inclusive total at the policy exchange rate;
    all of them stay ``None`` without a total.
    """
    total = summary.get("total_amount")
    if total is None:
        summary["tax_amount"] = None
        summary["total_with_tax"] = None
        summary["cny_total_with_tax"] = None
        return summary
    rate = float(policy.get("tax_rate") or 0.0)
    tax = round(float(total) * rate, 2)
    summary["tax_amount"] = tax
    summary["total_with_tax"] = round(float(total) + tax, 2)
    exchange_rate = _resolve_exchange_rate(
        policy.get("currency") or DEFAULT_CURRENCY,
        policy.get("exchange_rate"),
        DEFAULT_EXCHANGE_RATE,
    )
    summary["cny_total_with_tax"] = round(
        float(summary["total_with_tax"]) * exchange_rate, 2
    )
    return summary


# ------------------------------------------------------------------- quotas


def quota_payload(quota: QuotaItem) -> dict[str, Any]:
    created = quota.created_at
    updated = quota.updated_at
    return {
        "id": quota.id,
        "name": quota.name,
        "spec": quota.spec or "",
        "unit": quota.unit or "",
        "unit_price": round(float(quota.unit_price or 0.0), 4),
        "category": quota.category or "",
        "note": quota.note or "",
        "created_at": created.isoformat() if created else None,
        "updated_at": updated.isoformat() if updated else None,
    }


def match_quotas(
    item: dict[str, Any], quotas: list[QuotaItem], *, limit: int | None = None
) -> list[tuple[float, QuotaItem]]:
    """Score every quota against one BOQ-like item, best first (threshold 0.75)."""
    scored: list[tuple[float, QuotaItem]] = []
    for quota in quotas:
        score = match_score(item, quota)
        if score >= MATCH_THRESHOLD:
            scored.append((score, quota))
    scored.sort(key=lambda pair: (-pair[0], pair[1].name, pair[1].id))
    if limit is not None:
        scored = scored[:limit]
    return scored


def quota_fill(
    db: Session,
    project: Project,
    *,
    package_id: str | None = None,
    only_missing: bool = True,
    dry_run: bool = True,
) -> dict[str, Any]:
    """Propose (and optionally write) administrator-maintained quota prices.

    A row only receives a price when a quota scores at least
    :data:`MATCH_THRESHOLD`; the application never derives or invents a price.
    """
    snapshot = get_snapshot(db, project.id, package_id)
    if snapshot is None:
        raise BoqConflictError("尚未上传工程量清单，请先导入清单文件")
    quotas = list(db.scalars(select(QuotaItem).order_by(QuotaItem.name, QuotaItem.id)))
    items = list(snapshot.items or [])
    prices = dict(snapshot.prices or {})
    ignored = set(snapshot.ignored or [])
    proposals: list[dict[str, Any]] = []
    applied = 0
    for item in items:
        key = f"{snapshot.sheet}!{item['row']}"
        if key in ignored:
            continue
        best = match_quotas(item, quotas, limit=1)
        if not best:
            continue
        score, quota = best[0]
        proposals.append(
            {
                "boq_row": item["row"],
                "name": item.get("name", ""),
                "quota_id": quota.id,
                "quota_name": quota.name,
                "unit_price": round(float(quota.unit_price or 0.0), 4),
                "score": round(float(score), 4),
            }
        )
        if dry_run:
            continue
        if only_missing and _price_payload(item, prices.get(key)) is not None:
            continue
        prices[key] = round(float(quota.unit_price or 0.0), 4)
        applied += 1
    if not dry_run and applied:
        snapshot.prices = prices
        db.flush()
    return {"proposals": proposals, "applied": applied}


def adjust_prices(
    db: Session, project: Project, *, package_id: str | None = None
) -> dict[str, Any]:
    """Multiply every entered unit price by the policy factor and write it back."""
    snapshot = get_snapshot(db, project.id, package_id)
    if snapshot is None:
        raise BoqConflictError("尚未上传工程量清单，请先导入清单文件")
    policy = get_price_policy(project)
    factor = float(policy["factor"])
    digits = int(policy["round_digits"])
    prices = dict(snapshot.prices or {})
    rows = 0
    for item in list(snapshot.items or []):
        key = f"{snapshot.sheet}!{item['row']}"
        price = _price_payload(item, prices.get(key))
        if price is None:
            continue
        prices[key] = round(float(price["unit_price"]) * factor, digits)
        rows += 1
    if rows == 0:
        raise BoqConflictError("该包件尚未录入任何单价，无法调价")
    snapshot.prices = prices
    db.flush()
    return {
        "rows": rows,
        "factor": factor,
        "payload": build_payload(db, project.id, package_id),
    }
